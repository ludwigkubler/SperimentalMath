def dot_product(w, v):
    return sum(w[i] * v[i] for i in range(len(v)))

def sample_weight_vector(n: int) -> Tuple[float, ...]:
    # Each coordinate: sign * exp(±10) * uniform?
    # But exp(±10) is huge, so we do: w_i = random.choice([-1,1]) * random.expovariate(1) * (1000 if random.choice([True,False]) else 0.001)
    # But simpler: w_i = random.gauss(0,1) * (1e-10 if random.random() < 0.5 else 1e10)
    w = []
    for _ in range(n):
        if random.random() < 0.5:
            w.append(random.gauss(0, 1) * 1e10)
        else:
            w.append(random.gauss(0, 1) * 1e-10)
    return tuple(w)

def solve_set_cover(sets: List[Set[Tuple[int,int]]], universe: Set[Tuple[int,int]]):
    if not universe:
        return 0
    if not sets:
        return float('inf')
    
    # DP over subsets of universe
    clauses_list = sorted(universe)
    clause_to_index = {cl: idx for idx, cl in enumerate(clauses_list)}
    m = len(clauses_list)
    # Represent subsets as bit masks
    dp = [float('inf')] * (1 << m)
    dp[0] = 0
    
    # Precompute mask for each set
    set_masks = []
    for s in sets:
        mask = 0
        for cl in s:
            if cl in clause_to_index:
                mask |= (1 << clause_to_index[cl])
        set_masks.append(mask)
    
    for mask in range(1 << m):
        if dp[mask] == float('inf'):
            continue
        for smask in set_masks:
            new_mask = mask | smask
            if dp[new_mask] > dp[mask] + 1:
                dp[new_mask] = dp[mask] + 1
    
    return dp[(1 << m) - 1]

