            w = sample_weight_vector(n_vars)
            # Find minimizing vertex: argmin w·v over sat_assignments
            best_val = None
            best_vertex = None
            for v in sat_assignments:
                val = dot_product(w, v)
                if best_val is None or val < best_val:
                    best_val = val
                    best_vertex = v
                elif val == best_val:
                    # lex tie-breaking: take smallest tuple
                    if v < best_vertex:
                        best_vertex = v
            # What clauses are covered by best_vertex?
            # Clause (i,j) is covered if best_vertex[i] == 1 and best_vertex[j] == 1
