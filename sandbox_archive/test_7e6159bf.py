        if not sat_assignments:
            continue  # skip unsat, though shouldn't happen

        # Compute D(f)
        Df = decision_tree_complexity(truth_table, n_vars)

        # Sample 100 weight vectors
        covered_clause_sets = []  # list of sets of clauses covered by each degeneration
        weight_trials = 100
