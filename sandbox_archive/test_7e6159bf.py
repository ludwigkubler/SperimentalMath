def all_monotone_2cnf(n: int):
    """Generate all monotone 2-CNF formulas with up to n variables.
    Each clause is (x_i OR x_j), i <= j, and we consider nonempty subsets of clauses.
    We return the clause sets and the induced Boolean functions as truth tables.
    """
    if n == 0:
        return []
    clauses = []
    for i in range(n):
        for j in range(i, n):
            clauses.append((i, j))
    
    formulas = []
    # Skip empty formula (always true) and full clause set (may be unsat)
    for k in range(1, len(clauses) + 1):
        for clause_set in itertools.combinations(clauses, k):
            # Build truth table for f
            truth_table = []
            for assignment in itertools.product([0,1], repeat=n):
                sat = True
                for (i,j) in clause_set:
                    if assignment[i] == 0 and assignment[j] == 0:
                        sat = False
                        break
                truth_table.append(sat)
            formulas.append((clause_set, tuple(truth_table), n))
    return formulas

@lru_cache(maxsize=None)
def decision_tree_complexity(truth_table: Tuple[bool], n: int) -> int:
    """Compute decision tree complexity D(f) for a Boolean function on n bits."""
    if all(truth_table):
        return 0
    if not any(truth_table):
        return 0
    
    def can_shatter(assignment: Tuple[int, ...], fixed: Dict[int, int]) -> bool:
        for var, val in fixed.items():
            if assignment[var] != val:
                return False
        return True

    def D_recursive(remaining_vars: Tuple[int, ...], partial_assign: Tuple[Tuple[int, int], ...]) -> int:
        # partial_assign: list of (var, value)
        fixed = dict(partial_assign)
        relevant = [i for i, tt in enumerate(truth_table) 
                   if can_shatter(tuple((i >> (n-1-b)) & 1 for b in range(n)), fixed)]
        
        outcomes = set(truth_table[i] for i in relevant)
        if len(outcomes) <= 1:
            return 0
        
        best = float('inf')
        for var in remaining_vars:
            not_fixed = True
            for v in [0,1]:
                new_assign = tuple(sorted(partial_assign + ((var, v),)))
                new_vars = tuple(vv for vv in remaining_vars if vv != var)
                cost = 1 + D_recursive(new_vars, new_assign)
                if cost < best:
                    best = cost
        return best
    
    vars_tuple = tuple(range(n))
    return D_recursive(vars_tuple, tuple())

def build_polytope(truth_table: Tuple[bool], n: int) -> List[Tuple[int, ...]]:
    """Return the list of satisfying assignments (as tuples) for the function."""
    pts = []
    for i, sat in enumerate(truth_table):
        if sat:
            assignment = tuple((i >> (n-1-b)) & 1 for b in range(n))
            pts.append(assignment)
    return pts

